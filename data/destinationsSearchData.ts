/**
 * Searches local comprehensive dataset with instant fuzzy matching,
 * typo tolerance, and alias checking.
 */
export function searchLocalDestinations(query: string): DestinationItem[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return [];

  return comprehensiveDestinations
    .filter((item) => {
      const nameMatch = item.name.toLowerCase().includes(clean);
      const stateMatch = item.state?.toLowerCase().includes(clean);
      const countryMatch = item.country.toLowerCase().includes(clean);
      const tagMatch = item.tag?.toLowerCase().includes(clean);
      const aliasMatch = item.aliases.some((a) => a.toLowerCase().includes(clean) || clean.includes(a.toLowerCase()));

      return nameMatch || stateMatch || countryMatch || tagMatch || aliasMatch;
    })
    .slice(0, 8);
}
